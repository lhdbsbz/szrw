// Package registrygen 是「单进程微服务」脚手架的接线生成器，约定优先、零配置：
//
//   - 对每个 proto 服务生成 gen/local_service_center/<svc>.go（进程内 gRPC 注册 + 客户端获取）
//   - 聚合生成 gen/wiring/wiring_gen.go（BootAll + Gate + RegisterGateways），main.go / router.go 永不改动
//   - 生成 gen/startup/startup.go：启动钩子契约（只有类型，没有实现）
//
// 启动顺序约束只跟装配顺序有关，所以放行逻辑随 BootAll 一起生成（Gate），不引入手写调度包。
//
// 一切路径从 proto 的 go_package 推导：go_package 必须形如 <module>/gen/proto/<pkg>，
// 实现包约定为 <module>/microservice/<snake(服务名)>_service，导出 var Service 和
// func Main(ctx, start)。
// 布局与开关全部来自仓库根 codegen.yaml 的 registry 段（见 internal/config），
// 插件参数只接受 config=<path>：未知键、版本不符、越界路径一律报错。
package registrygen

