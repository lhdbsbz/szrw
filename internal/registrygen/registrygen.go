// ---- 布局约定全部在 config.go（codegen.yaml 的 registry 段）----
// 默认值 = 本框架的标准布局；项目只在 codegen.yaml 里覆盖与默认不同的部分。
// 生成物必须随时可整体删除并由 protoc 完整重建。

// startupTemplate 是启动钩子契约：只有类型，没有实现。
const startupTemplate = `// Code generated by protoc-gen-szrw-codegen. DO NOT EDIT.

package startup

import "context"

// Func 把需要在「全部服务注册完成」之后才运行的任务挂到启动器上。
//
//	start("posting.review", loop)   // loop 形如 func(context.Context)，长期运行，ctx 结束才返回
//
// 实现是生成物里的 wiring.Gate：BootAll 末尾统一放行；loop 返回即视为退出。
type Func func(name string, loop func(context.Context))
`

// wiringTemplate 是接线文件的唯一模板：BootAll + Gate + RegisterGateways + 流式方法表。
const wiringTemplate = `// Code generated by protoc-gen-szrw-codegen. DO NOT EDIT.

package {{.Package}}

import (
	"context"
	"sync"

	"github.com/grpc-ecosystem/grpc-gateway/v2/runtime"
	"google.golang.org/grpc"
	"google.golang.org/grpc/credentials/insecure"

	{{printf "%q" .CoreImport}}
{{range .Imports}}
	{{.Alias}} {{printf "%q" .Path}}
{{- end}}
)

// BootAll 同步注册全部进程内服务；各 Main 经 gate.Start 挂载的循环在末尾统一放行。
func BootAll(ctx context.Context) {
	gate := NewGate(ctx)
{{- range .Services}}
	{{.ImplSeg}}.Main(ctx, gate.Start)
{{- end}}
	gate.Ready()
}

// Gate 是「装配完成」的放行开关：Start 挂载的循环在 Ready 之前一律阻塞。
type Gate struct {
	ctx   context.Context
	ready chan struct{}
	once  sync.Once
}

// NewGate 创建未放行的 Gate；独立脚本不走 BootAll 时可用它自己挂载。
func NewGate(ctx context.Context) *Gate {
	return &Gate{ctx: ctx, ready: make(chan struct{})}
}

// Start 挂载长期循环：Ready 之前不运行，ctx 结束即停。方法值即 startup.Func。
func (g *Gate) Start(_ string, loop func(context.Context)) {
	go func() {
		select {
		case <-g.ready:
		case <-g.ctx.Done():
			return
		}
		loop(g.ctx)
	}()
}

// Ready 放行全部已挂载的循环；可重复调用。
func (g *Gate) Ready() {
	g.once.Do(func() { close(g.ready) })
}

// RegisterGateways 注册所有带 HTTP 网关的服务到 grpc-gateway mux。
func RegisterGateways(ctx context.Context, mux *runtime.ServeMux) {
	// 网关到服务的这一跳也是真实 gRPC 调用，必须带调用方拦截器：
	// 否则 HTTP 入口写进 ctx 的 trace / 身份不会传下去，访问日志也只剩服务端半边。
	opts := []grpc.DialOption{
		grpc.WithTransportCredentials(insecure.NewCredentials()),
		grpc.WithChainUnaryInterceptor(core.MetadataCallerInterceptor),
		grpc.WithChainStreamInterceptor(core.MetadataStreamCallerInterceptor),
		grpc.WithDefaultCallOptions(
			grpc.MaxCallRecvMsgSize(core.MaxMsgSize),
			grpc.MaxCallSendMsgSize(core.MaxMsgSize),
		),
	}
{{- range .Gateways}}
	_ = {{.ProtoPkg}}.Register{{.FullName}}HandlerFromEndpoint(ctx, mux,
		core.GlobalRegistry.MustDiscover({{.ProtoPkg}}.{{.FullName}}_ServiceDesc), opts)
{{- end}}
}

// StreamingGatewayMethods 是走 grpc-gateway mux 的 server-streaming 方法全名集合，
// 响应按 SSE 逐块直出、不套统一信封。由 server-streaming + google.api.http 自动判定。
var StreamingGatewayMethods = map[string]bool{
{{- range .Streaming}}
	{{printf "%q" .}}: true,
{{- end}}
}
`

// 每服务注册文件模板（内嵌，gofmt 兜底格式化）
const registryTemplate = `// Code generated by protoc-gen-szrw-codegen. DO NOT EDIT.

package {{.PackageName}}

import (
	"context"
	"net"

	"{{.ProtoImportPath}}"
	{{printf "%q" .CoreImport}}
	"google.golang.org/grpc"
	"google.golang.org/grpc/credentials/insecure"
)

// Register{{.ServiceName}}Service 注册{{.ServiceName}}服务
func Register{{.ServiceName}}Service(ctx context.Context, service {{.ProtoPackageName}}.{{.ProtoServiceName}}ServiceServer) {
	serviceInfo := {{.ProtoPackageName}}.{{.ProtoServiceName}}Service_ServiceDesc

	// 检查服务是否已注册
	if _, ok := core.GlobalRegistry.Discover(serviceInfo); ok {
		panic("服务重复注册: " + string(serviceInfo.ServiceName))
	}

	// 监听随机端口（同步进行，避免注册时序竞态）
	lis, err := net.Listen("tcp", "localhost:0")
	if err != nil {
		panic("监听端口失败: " + err.Error())
	}

	// 注册服务地址（同步进行，确保调用端能立即 Discover 到）
	core.GlobalRegistry.RegisterAddr(serviceInfo, lis.Addr().String())

	go func() {
		// 创建gRPC服务器
		server := grpc.NewServer(
			grpc.ChainUnaryInterceptor(core.MetadataCalleeInterceptor),
			grpc.ChainStreamInterceptor(core.MetadataStreamCalleeInterceptor),
			grpc.MaxRecvMsgSize(core.MaxMsgSize),
			grpc.MaxSendMsgSize(core.MaxMsgSize),
		)
		go func() {
			<-ctx.Done()
			server.GracefulStop()
		}()
		// 注册服务
		{{.ProtoPackageName}}.Register{{.ProtoServiceName}}ServiceServer(server, service)

		// 启动服务器
		if err = server.Serve(lis); err != nil {
			panic("服务启动失败: " + err.Error())
		}
	}()
}

// Get{{.ServiceName}}Service 获取{{.ServiceName}}服务客户端
func Get{{.ServiceName}}Service() {{.ProtoPackageName}}.{{.ProtoServiceName}}ServiceClient {
	serviceInfo := {{.ProtoPackageName}}.{{.ProtoServiceName}}Service_ServiceDesc

	// 尝试获取已缓存的客户端
	if client, exists := core.GlobalRegistry.GetClient(serviceInfo); exists {
		return client.({{.ProtoPackageName}}.{{.ProtoServiceName}}ServiceClient)
	}

	// 发现服务地址
	addr := core.GlobalRegistry.MustDiscover(serviceInfo)

	// 创建连接
	conn, err := grpc.NewClient(addr,
		grpc.WithTransportCredentials(insecure.NewCredentials()),
		grpc.WithChainUnaryInterceptor(core.MetadataCallerInterceptor),
		grpc.WithChainStreamInterceptor(core.MetadataStreamCallerInterceptor),
		grpc.WithDefaultCallOptions(
			grpc.MaxCallRecvMsgSize(core.MaxMsgSize),
			grpc.MaxCallSendMsgSize(core.MaxMsgSize),
		),
	)
	if err != nil {
		panic("创建客户端连接失败: " + err.Error())
	}

	// 创建客户端
	client := {{.ProtoPackageName}}.New{{.ProtoServiceName}}ServiceClient(conn)

	// 缓存客户端
	core.GlobalRegistry.RegisterClient(serviceInfo, client)

	return client
}

// Get{{.ServiceName}}ServiceAddressInfo 获取{{.ServiceName}}服务的具体地址
func Get{{.ServiceName}}ServiceAddressInfo() string {
	serviceInfo := {{.ProtoPackageName}}.{{.ProtoServiceName}}Service_ServiceDesc

	// 尝试获取已注册的地址
	if addr, exists := core.GlobalRegistry.Discover(serviceInfo); exists {
		return addr
	}
	return ""
}
`

type registryData struct {
	ServiceName      string // Go注册函数名称前缀，如 OpenApiMemory
	ProtoServiceName string // Proto服务名称前缀，如 Memory (如果是 MemoryService)
	ProtoPackageName string // proto 生成包名，如 user
	ProtoImportPath  string // proto 生成包导入路径
	ModuleRoot       string // 从 go_package 推导的 module 根
	PackageName      string // 生成物的包名（= registry_dir 的目录名）
	CoreImport       string // 运行时注册表包的完整导入路径
}

// wiringService 聚合接线所需的单个服务信息。
type wiringService struct {
	FullName     string // 完整服务名，如 UserService（用于网关注册函数名）
	ProtoPkg     string // proto 包名，如 user
	ProtoImport  string // proto 生成包导入路径
	ImplSeg      string // 实现包目录段，如 user_service（同时用作 import 别名）
	ImplImport   string // 实现包完整导入路径
	HasGateway   bool   // 是否有带 google.api.http 注解的方法
	HasHttpRoute bool   // 是否具有 http 路由方法（包含 google.api.http），以此决定是否生成 RegisterXxxHandlerFromEndpoint
	// 走 grpc-gateway mux 的纯 server-streaming 方法全名（/pkg.Service/Method）：响应须 SSE 直出、不套信封。
	StreamingHttpMethods []string
}

// Generate 生成注册文件、启动契约与装配骨架。
// 纯函数式：除了 gen 提供的内存文件表，只写常量声明的路径（加上 scaffold=write 时的骨架）。
func Generate(gen *protogen.Plugin, cfg *config.Registry) error {
	tmpl := template.Must(template.New("registry").Parse(registryTemplate))
	wiringTmpl := template.Must(template.New("wiring").Parse(wiringTemplate))

	// 契约规则先于生成：不合规就不产出任何文件，避免「半套生成物」被提交。
	// 没有开关——规则就是框架，不满足就是构建失败。
	if problems := validate.Run(gen); len(problems) > 0 {
		var b strings.Builder
		for _, p := range problems {
			fmt.Fprintf(&b, "  %s\n", p)
		}
		return fmt.Errorf("%d 处 proto 不合规（规则见 szrw-codegen/internal/validate）:\n%s", len(problems), b.String())
	}
	{
		moduleRoot := ""
		var wiring []wiringService
		var scaffoldTargets []scaffoldTarget
		for _, f := range gen.Files {
			if !f.Generate {
				continue
			}
			if len(f.Services) == 0 {
				continue
			}

			root, err := deriveModuleRoot(string(f.GoImportPath))
			if err != nil {
				return err
			}
			if moduleRoot == "" {
				moduleRoot = root
			} else if moduleRoot != root {
				return fmt.Errorf("service-registry: go_package 推导出不一致的 module 根: %q vs %q", moduleRoot, root)
			}

			for _, svc := range f.Services {
				if err := generateServiceRegistry(gen, f, svc, tmpl, root); err != nil {
					return err
				}
				ws := buildWiringService(f, svc, root)
				wiring = append(wiring, ws)
				protoRelPath := strings.TrimPrefix(string(f.GoImportPath), root+config.GenProtoSeg)
				scaffoldTargets = append(scaffoldTargets, scaffoldTarget{
					ImplDir:      strings.TrimPrefix(ws.ImplImport, root+"/"),
					ProtoFile:    f.Desc.Path(),
					Service:      svc,
					File:         f,
					ModuleRoot:   root,
					RegistryName: deriveRegistryName(protoRelPath, strings.TrimSuffix(string(svc.Desc.Name()), "Service")),
				})
			}
		}

		// 骨架生成必须在装配骨架之前：write 会补出缺失的方法文件，
		// 但不会改变本次生成的内存文件表（Go 侧编译在 protoc 之后）。
		if err := scaffold(gen, scaffoldTargets, cfg.WriteScaffold); err != nil {
			return err
		}

		// 启动钩子契约与「有几个服务」无关，每次都生成；接线文件只在有服务时才写。
		if err := generateStartup(gen); err != nil {
			return err
		}
		if len(wiring) == 0 {
			return nil
		}
		return generateWiring(gen, wiringTmpl, wiring, moduleRoot)
	}
}

// generateStartup 生成启动钩子契约包（只有类型，没有实现）。
func generateStartup(gen *protogen.Plugin) error {
	formatted, err := format.Source([]byte(startupTemplate))
	if err != nil {
		return fmt.Errorf("service-registry: format startup: %w", err)
	}
	g := gen.NewGeneratedFile(config.StartupOut, "")
	if _, err := g.Write(formatted); err != nil {
		return fmt.Errorf("service-registry: write %s: %w", config.StartupOut, err)
	}
	return nil
}

// deriveModuleRoot 从 go_package（如 github.com/x/backend/gen/proto/user）推导 module 根。
func deriveModuleRoot(goImportPath string) (string, error) {
	idx := strings.Index(goImportPath, config.GenProtoSeg)
	if idx <= 0 {
		return "", fmt.Errorf("service-registry: go_package %q 不符合约定 <module>%s<pkg>", goImportPath, config.GenProtoSeg)
	}
	return goImportPath[:idx], nil
}

func generateServiceRegistry(gen *protogen.Plugin, file *protogen.File, service *protogen.Service, tmpl *template.Template, moduleRoot string) error {
	protoServiceName := strings.TrimSuffix(string(service.Desc.Name()), "Service")

	protoRelPath := strings.TrimPrefix(string(file.GoImportPath), moduleRoot+config.GenProtoSeg)
	registryName := deriveRegistryName(protoRelPath, protoServiceName)

	data := registryData{
		ServiceName:      registryName,
		ProtoServiceName: protoServiceName,
		ProtoPackageName: string(file.GoPackageName),
		ProtoImportPath:  string(file.GoImportPath),
		ModuleRoot:       moduleRoot,
		PackageName:      config.RegistryPackage(),
		CoreImport:       config.CoreImport(),
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return fmt.Errorf("service-registry: execute template: %w", err)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("service-registry: format %s: %w", registryName, err)
	}

	rel := filepath.Join(config.RegistryDir, fmt.Sprintf("%s.go", naming.LowerFirst(registryName)))
	g := gen.NewGeneratedFile(rel, "")
	if _, err := g.Write(formatted); err != nil {
		return fmt.Errorf("service-registry: write %s: %w", rel, err)
	}
	return nil
}

// buildWiringService 从 proto 服务推导聚合接线所需信息。
func buildWiringService(file *protogen.File, service *protogen.Service, moduleRoot string) wiringService {
	full := string(service.Desc.Name()) // UserService

	protoRelPath := strings.TrimPrefix(string(file.GoImportPath), moduleRoot+config.GenProtoSeg)
	seg := strings.ReplaceAll(protoRelPath, "/", "_") + config.ImplSuffix
	parts := strings.Split(protoRelPath, "/")
	var implPath string
	if len(parts) > 1 {
		implPath = strings.Join(parts[:len(parts)-1], "/") + "/" + parts[len(parts)-1]
	} else {
		implPath = protoRelPath
	}

	var streamingHttp []string
	pkgName := string(file.Desc.Package()) // proto 包名，如 proto.story
	for _, method := range service.Methods {
		// 纯 server-streaming 且挂了 google.api.http：走 grpc-gateway mux、按 SSE 直出，
		// 须在响应改写处跳过统一信封。全名格式与运行时 runtime.RPCMethod 一致：/pkg.Service/Method。
		if httpx.MethodHasHTTP(method) && method.Desc.IsStreamingServer() && !method.Desc.IsStreamingClient() {
			streamingHttp = append(streamingHttp,
				fmt.Sprintf("/%s.%s/%s", pkgName, full, string(method.Desc.Name())))
		}
	}

	hasGateway := httpx.ServiceHasHTTP(service)

	return wiringService{
		FullName:             full,
		ProtoPkg:             strings.ReplaceAll(protoRelPath, "/", "_"),
		ProtoImport:          string(file.GoImportPath),
		ImplSeg:              seg,
		ImplImport:           moduleRoot + "/" + config.ImplRoot + "/" + implPath,
		HasGateway:           hasGateway,
		HasHttpRoute:         httpx.ServiceHasHTTP(service),
		StreamingHttpMethods: streamingHttp,
	}
}

// wiringImport 是一行 import（实现包与 proto 包合并后按路径排序）。
type wiringImport struct {
	Alias string
	Path  string
}

// wiringData 是 wiringTemplate 的渲染数据。
type wiringData struct {
	Package    string
	CoreImport string
	Imports    []wiringImport  // 实现包 + 网关 proto 包，按 Path 排序
	Services   []wiringService // Main 调用顺序 = proto 遍历顺序
	Gateways   []wiringService // 其中有 HTTP 路由的，才进 RegisterGateways
	Streaming  []string        // 排序后的流式方法全名
}

// renderWiring 把服务清单渲染成 gofmt 后的接线源码（纯函数，不碰 protogen）。
func renderWiring(tmpl *template.Template, svcs []wiringService, moduleRoot string) ([]byte, error) {
	// 收集 import（alias -> path）：实现包全部服务都要，proto 包只给带网关的服务。
	implSet := map[string]string{}
	protoSet := map[string]string{}
	for _, s := range svcs {
		implSet[s.ImplSeg] = s.ImplImport
		if s.HasGateway {
			protoSet[s.ProtoPkg] = s.ProtoImport
		}
	}

	data := wiringData{
		Package:    config.WiringPackage(),
		CoreImport: config.CoreImport(),
		Services:   svcs,
	}
	for a, p := range implSet {
		data.Imports = append(data.Imports, wiringImport{Alias: a, Path: p})
	}
	for a, p := range protoSet {
		data.Imports = append(data.Imports, wiringImport{Alias: a, Path: p})
	}
	sort.Slice(data.Imports, func(i, j int) bool { return data.Imports[i].Path < data.Imports[j].Path })

	for _, s := range svcs {
		if s.HasHttpRoute {
			data.Gateways = append(data.Gateways, s)
		}
		data.Streaming = append(data.Streaming, s.StreamingHttpMethods...)
	}
	sort.Strings(data.Streaming)

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("service-registry: execute wiring template: %w", err)
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("service-registry: format wiring: %w\n---\n%s", err, buf.String())
	}
	return formatted, nil
}

// generateWiring 写出单份聚合接线文件。
func generateWiring(gen *protogen.Plugin, tmpl *template.Template, svcs []wiringService, moduleRoot string) error {
	src, err := renderWiring(tmpl, svcs, moduleRoot)
	if err != nil {
		return err
	}
	g := gen.NewGeneratedFile(config.WiringOut, "")
	if _, err := g.Write(src); err != nil {
		return fmt.Errorf("service-registry: write %s: %w", config.WiringOut, err)
	}
	return nil
}

func deriveRegistryName(protoRelPath string, protoServiceName string) string {
	parts := strings.Split(protoRelPath, "/")
	if len(parts) > 1 {
		var prefixParts []string
		for _, p := range parts[:len(parts)-1] {
			prefixParts = append(prefixParts, naming.UpperCamel(p))
		}
		return strings.Join(prefixParts, "") + protoServiceName
	}
	return protoServiceName
}
