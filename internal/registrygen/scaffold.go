// 框架对实现文件只有一条硬规则：一个 rpc 一个文件，文件名由 rpc 决定。
//
//	microservice/user/UpdateNickName  →  microservice/user/update_nick_name.go
//
// 这条规则之所以值得强制，是因为它让「定位」变成查表而不是搜索：想知道某个
// rpc 在哪，不需要知道前人怎么分文件。代价是文件多，收益是确定。
//
// 生成器只做两件事：缺失的补出来（write），不合规的报出来（check/write 都报）。
// 它不猜人的意图，也不提供「你自己合并」的逃生门——框架的规则不靠记，靠构建失败。
//
// 两种生成物用同一个文法的动词区分：
//
//	// Code generated by  <tool> ... DO NOT EDIT.             → 不可编辑，每次重建
//	// Code scaffolded by <tool> from <proto>:<Service>/<Rpc> → 归你所有，只补不覆盖

const scaffoldHeaderFormat = "// Code scaffolded by protoc-gen-szrw-codegen from %s:%s/%s\n" +
	"// 归你所有：生成器只在文件缺失时创建它，之后不再覆盖。\n\n"

// scaffoldServiceHeaderFormat 是 rpc.go（服务自身形状）的头：它属于整个服务，不属于某个 rpc。
const scaffoldServiceHeaderFormat = "// Code scaffolded by protoc-gen-szrw-codegen from %s:%s\n" +
	"// 归你所有：生成器只在文件缺失时创建它，之后不再覆盖。\n\n"

// scaffoldTarget 是一个待检查的实现目录与其 proto 服务。
type scaffoldTarget struct {
	ImplDir      string // 相对 protoc 工作目录（= 仓库根）
	ProtoFile    string // protoc 报告的 proto 路径，仅用于文件头溯源
	Service      *protogen.Service
	File         *protogen.File
	ModuleRoot   string // 从 go_package 推导的 module 根
	RegistryName string // Register<X>Service 里的 X（proto 相对路径可消歧）
}

// implPackageState 是目标目录的静态事实。
type implPackageState struct {
	PkgName       string
	HasServerType bool
	Methods       map[string]string // 处理器方法名 → 声明它的文件名（不含目录）
	DeclaredIn    map[string]string // 文件名 → 它声明的处理器方法名
}

// scaffold 检查实现文件归属，write 时额外补出完全缺失的文件。
// 没有 off：归属检查是框架规则，不能关。write 只来自命令行参数（本地加 RPC 用）。
func scaffold(gen *protogen.Plugin, targets []scaffoldTarget, write bool) error {
	if len(targets) == 0 {
		return nil
	}

	pkgNames := goPackageNames(gen)

	var violations, missing []string
	created := 0

	// 域边界：先算出「哪些目录是服务根」，再整体扫一遍 import。
	// 这与逐目录的实现文件检查无关，一次扫描覆盖整个 ImplRoot。
	serviceRoots := map[string]bool{}
	for _, t := range targets {
		serviceRoots[strings.TrimPrefix(t.ImplDir, config.ImplRoot+"/")] = true
	}
	if boundaryViolations, err := checkBoundaries(serviceRoots); err != nil {
		return err
	} else {
		violations = append(violations, boundaryViolations...)
	}

	for _, t := range targets {
		state, err := inspectImplDir(t.ImplDir)
		if err != nil {
			return err
		}
		// 目录本身还不是框架服务：write 时把 rpc.go 的骨架一起补出来，
		// 这样「加一个域」= 写 proto，其余全自动。
		if state.PkgName == "" || !state.HasServerType {
			done, violation, absent, err := scaffoldServiceFile(t, state, write)
			if err != nil {
				return err
			}
			if violation != "" {
				violations = append(violations, violation)
				continue
			}
			if absent != "" {
				missing = append(missing, absent)
				continue
			}
			if !done {
				continue
			}
			created++
			state, err = inspectImplDir(t.ImplDir)
			if err != nil {
				return err
			}
		}

		for _, method := range t.Service.Methods {
			name := string(method.Desc.Name())
			label := string(t.Service.Desc.Name()) + "." + name
			want := naming.Snake(name) + ".go"
			path := filepath.Join(t.ImplDir, want)

			declared, hasMethod := state.Methods[name]
			switch {
			case hasMethod && declared != want:
				violations = append(violations, fmt.Sprintf("%s/%s 实现 %s，框架要求 %s", t.ImplDir, declared, label, want))

			case hasMethod: // 已在正确文件里
				// 同一文件里还声明了别的 rpc：一个文件只能有一个 rpc。
				if other, ok := state.DeclaredIn[want]; ok && other != name {
					violations = append(violations, fmt.Sprintf("%s 声明了 %s，但它属于 %s/%s", path, other, t.ImplDir, naming.Snake(other)+".go"))
				}

			case fileExists(path):
				violations = append(violations, fmt.Sprintf("%s 已存在但没有实现 %s：内容与文件名不符，请人工处理", path, label))

			case method.Desc.IsStreamingClient() || method.Desc.IsStreamingServer():
				missing = append(missing, label+"（流式 rpc 的骨架形态不同，需手写 "+want+"）")

			case !write:
				missing = append(missing, fmt.Sprintf("%s → %s", label, path))

			default:
				src, err := scaffoldSource(t, method, state.PkgName, pkgNames)
				if err != nil {
					return err
				}
				if err := os.WriteFile(path, src, 0o644); err != nil {
					return fmt.Errorf("写入骨架 %s: %w", path, err)
				}
				created++
				fmt.Fprintf(os.Stderr, "scaffold: + %s (%s)\n", path, label)
			}
		}
	}

	sort.Strings(violations)
	sort.Strings(missing)
	for _, v := range violations {
		fmt.Fprintf(os.Stderr, "scaffold: ! %s\n", v)
	}
	for _, m := range missing {
		fmt.Fprintf(os.Stderr, "scaffold: ? 缺失实现 %s\n", m)
	}
	if len(violations) > 0 {
		return fmt.Errorf("%d 处实现文件不符合「一个 rpc 一个文件」，见上方日志", len(violations))
	}
	if len(missing) > 0 && !write {
		return fmt.Errorf("%d 个 rpc 没有实现（scaffold=check）", len(missing))
	}
	if created > 0 {
		fmt.Fprintf(os.Stderr, "scaffold: 创建了 %d 个骨架文件，填完实现再提交\n", created)
	}
	return nil
}

// scaffoldServiceFile 补出「服务自身的形状」：rpc.go（var Service / Main / ServiceServer）。
// 这样加一个域就是：写 proto → 跑构建 → 得到 rpc.go + 每个 rpc 的骨架文件。
func scaffoldServiceFile(t scaffoldTarget, state implPackageState, write bool) (bool, string, string, error) {
	path := filepath.Join(t.ImplDir, "rpc.go")

	if fileExists(path) {
		return false, fmt.Sprintf("%s 已存在但没有 type ServiceServer：内容与文件名不符，请人工处理", path), "", nil
	}
	if !write {
		return false, "", fmt.Sprintf("%s 缺少 rpc.go（var Service / Main / ServiceServer）", t.ImplDir), nil
	}

	src, err := serviceFileSource(t)
	if err != nil {
		return false, "", "", err
	}
	if err := os.MkdirAll(t.ImplDir, 0o755); err != nil {
		return false, "", "", err
	}
	if err := os.WriteFile(path, src, 0o644); err != nil {
		return false, "", "", fmt.Errorf("写入 %s: %w", path, err)
	}
	fmt.Fprintf(os.Stderr, "scaffold: + %s (%sService)\n", path, t.RegistryName)
	return true, "", "", nil
}

// serviceFileSource 生成 rpc.go：只含不可推导为零的接线条目，没有任何业务。
func serviceFileSource(t scaffoldTarget) ([]byte, error) {
	pkg := filepath.Base(t.ImplDir)

	type imp struct{ alias, path string }
	imports := []imp{
		{alias: config.RegistryPackage(), path: t.ModuleRoot + "/" + filepath.ToSlash(config.RegistryDir)},
		{alias: string(t.File.GoPackageName), path: string(t.File.GoImportPath)},
		{alias: config.PackageNameOf(filepath.Dir(config.StartupOut)), path: t.ModuleRoot + "/" + filepath.ToSlash(filepath.Dir(config.StartupOut))},
	}
	sort.Slice(imports, func(i, j int) bool { return imports[i].path < imports[j].path })

	var b strings.Builder
	fmt.Fprintf(&b, scaffoldServiceHeaderFormat, t.ProtoFile, t.Service.Desc.Name())
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	b.WriteString("import (\n\t\"context\"\n\n")
	for _, im := range imports {
		if im.alias == filepath.Base(im.path) {
			fmt.Fprintf(&b, "\t%q\n", im.path)
			continue
		}
		fmt.Fprintf(&b, "\t%s %q\n", im.alias, im.path)
	}
	b.WriteString(")\n\n")

	b.WriteString("var Service = &ServiceServer{}\n\n")
	b.WriteString("// Main 注册本服务。后台循环用 start(...) 挂载，由 wiring.BootAll 统一放行。\n")
	fmt.Fprintf(&b, "func Main(ctx context.Context, start startup.Func) {\n")
	fmt.Fprintf(&b, "\t%s.Register%sService(ctx, Service)\n", config.RegistryPackage(), t.RegistryName)
	b.WriteString("}\n\n")
	b.WriteString("type ServiceServer struct {\n")
	fmt.Fprintf(&b, "\t%s.Unimplemented%sServer\n", string(t.File.GoPackageName), t.Service.Desc.Name())
	b.WriteString("}\n")

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("格式化服务骨架失败: %w", err)
	}
	return formatted, nil
}

func fileExists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}

// inspectImplDir 读取目标目录的包名、是否有 ServiceServer、每个处理器方法声明在哪个文件。
// 只读自己要写的目录：生成器不从别的代码反推布局。
func inspectImplDir(dir string) (implPackageState, error) {
	state := implPackageState{Methods: map[string]string{}, DeclaredIn: map[string]string{}}

	entries, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return state, nil
		}
		return state, err
	}

	fset := token.NewFileSet()
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, 0)
		if err != nil {
			return state, fmt.Errorf("解析 %s 失败: %w", filepath.Join(dir, name), err)
		}
		if state.PkgName == "" {
			state.PkgName = f.Name.Name
		}
		for _, decl := range f.Decls {
			switch d := decl.(type) {
			case *ast.FuncDecl:
				if d.Recv == nil || len(d.Recv.List) != 1 || !isServiceServerPtrExpr(d.Recv.List[0].Type) {
					continue
				}
				state.Methods[d.Name.Name] = name
				state.DeclaredIn[name] = d.Name.Name
			case *ast.GenDecl:
				if d.Tok != token.TYPE {
					continue
				}
				for _, spec := range d.Specs {
					ts, ok := spec.(*ast.TypeSpec)
					if ok && ts.Name.Name == "ServiceServer" {
						state.HasServerType = true
					}
				}
			}
		}
	}
	return state, nil
}

func isServiceServerPtrExpr(expr ast.Expr) bool {
	star, ok := expr.(*ast.StarExpr)
	if !ok {
		return false
	}
	id, ok := star.X.(*ast.Ident)
	return ok && id.Name == "ServiceServer"
}

// goPackageNames 给出「proto Go 导入路径 → 包名」，用于生成的 import 别名。
// protogen 已经算过这件事（go_package 里可能带 ;alias），不要自己猜。
func goPackageNames(gen *protogen.Plugin) map[string]string {
	out := map[string]string{}
	for _, f := range gen.Files {
		out[string(f.GoImportPath)] = string(f.GoPackageName)
	}
	return out
}

// scaffoldSource 生成一个「最小可编译」的骨架：只 import 签名用到的包。
func scaffoldSource(t scaffoldTarget, method *protogen.Method, pkgName string, pkgNames map[string]string) ([]byte, error) {
	// proto 消息在 Go 侧一律是指针；GoIdent 只给类型名，指针与 import 由这里补。
	imports := newImportSet(pkgNames)
	in := "*" + imports.qualify(method.Input.GoIdent)
	out := "*" + imports.qualify(method.Output.GoIdent)

	var b strings.Builder
	fmt.Fprintf(&b, scaffoldHeaderFormat, t.ProtoFile, t.Service.Desc.Name(), method.Desc.Name())
	fmt.Fprintf(&b, "package %s\n\n", pkgName)

	// 第一组只有标准库，第二组是 proto 包 + grpc（gofmt 惯用的分组方式）。
	b.WriteString("import (\n\t\"context\"\n\n")
	all := append(imports.sorted(), scaffoldImport{path: "google.golang.org/grpc/codes", alias: "codes", base: "codes"})
	all = append(all, scaffoldImport{path: "google.golang.org/grpc/status", alias: "status", base: "status"})
	sort.Slice(all, func(i, j int) bool { return all[i].path < all[j].path })
	for _, imp := range all {
		if imp.alias != imp.base {
			fmt.Fprintf(&b, "\t%s %q\n", imp.alias, imp.path)
			continue
		}
		fmt.Fprintf(&b, "\t%q\n", imp.path)
	}
	b.WriteString(")\n\n")

	label := string(t.Service.Desc.Name()) + "/" + string(method.Desc.Name())
	fmt.Fprintf(&b, "// %s 是生成的骨架，实现后请删掉这一行说明。\n", method.Desc.Name())
	fmt.Fprintf(&b, "func (s *ServiceServer) %s(ctx context.Context, req %s) (%s, error) {\n", method.GoName, in, out)
	fmt.Fprintf(&b, "\treturn nil, status.Error(codes.Unimplemented, \"未实现: %s\")\n}\n", label)

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("格式化骨架 %s 失败: %w", label, err)
	}
	return formatted, nil
}

// importSet 收集骨架签名需要的导入，并保证别名唯一。
type importSet struct {
	byPath  map[string]string // path → alias
	aliases map[string]string // alias → path
	names   map[string]string // path → 该包的 Go 包名
}

type scaffoldImport struct {
	path  string
	alias string
	base  string // 真实包名（决定是否需要显式别名）
}

func newImportSet(pkgNames map[string]string) *importSet {
	return &importSet{
		byPath:  map[string]string{},
		aliases: map[string]string{},
		names:   pkgNames,
	}
}

// qualify 返回「别名.类型名」，并登记该导入。
func (s *importSet) qualify(ident protogen.GoIdent) string {
	path := string(ident.GoImportPath)
	alias, ok := s.byPath[path]
	if !ok {
		base := s.names[path]
		if base == "" {
			parts := strings.Split(path, "/")
			base = parts[len(parts)-1]
		}
		alias = base
		for i := 2; ; i++ {
			if _, taken := s.aliases[alias]; !taken {
				break
			}
			alias = fmt.Sprintf("%s%d", base, i)
		}
		s.byPath[path] = alias
		s.aliases[alias] = path
	}
	return alias + "." + ident.GoName
}

func (s *importSet) sorted() []scaffoldImport {
	out := make([]scaffoldImport, 0, len(s.byPath))
	for path, alias := range s.byPath {
		base := s.names[path]
		if base == "" {
			parts := strings.Split(path, "/")
			base = parts[len(parts)-1]
		}
		out = append(out, scaffoldImport{path: path, alias: alias, base: base})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].path < out[j].path })
	return out
}
