// 输出路径配置：一个目标目录就是完整的一组事实，没有「全局默认 + 逐目标覆盖」。
type OutputPathConfig struct {
	Path          string // 输出路径
	ServiceImport string // 该目录下请求层（fetch 封装）的导入路径
	TypesRoot     string // ts-proto 类型根（仅 TS 使用）
}

// PluginConfig 是 codegen.yaml 的 frontend_api 段在生成器内部的形状。
type PluginConfig struct {
	TsOut []OutputPathConfig // TypeScript *Api.ts 输出目录
	JsOut []OutputPathConfig // JavaScript *Api.js 输出目录
}

// 方法信息结构体
type MethodInfo struct {
	MethodName        string // 方法名称
	HttpPath          string // HTTP 路径
	HttpMethod        string // HTTP 方法（post, get等，或者 websocket）
	RequestType       string // 请求类型名称（用于 TS）
	ResponseType      string // 响应类型名称（用于 TS）
	IsStreamingServer bool
	IsStreamingClient bool
	ReqBytesPaths     string // 请求消息的 bytes 字段路径 JS 字面量（如 [["audio","data"]]）；无则空串
	RespBytesPaths    string // 响应消息的 bytes 字段路径 JS 字面量；无则空串
}

// 服务信息结构体
type ServiceInfo struct {
	ServiceName   string              // 服务名称（去掉 Service 后缀）
	ApiFileName   string              // API 文件名（如 productApi）
	Methods       []MethodInfo        // 方法列表
	ServiceImport string              // service 模块路径
	TypesRoot     string              // ts-proto 类型根路径前缀
	TypeImports   map[string][]string // importPath -> sorted type names
	ProtoFilePath string              // proto 源文件路径
}

// generatedHeader 是每个生成文件的第一行：明确告知「这是生成物，不要手改」。
const generatedHeader = "// Code generated by protoc-gen-szrw-codegen. DO NOT EDIT.\n\n"

// toPluginConfig 把共享的 frontend_api 配置段转成本文件使用的形状。
// 保留这层适配，是为了让生成逻辑不直接依赖配置包的结构。
func toPluginConfig(f *config.FrontendAPI) *PluginConfig {
	cfg := &PluginConfig{}
	for _, t := range f.Targets {
		item := OutputPathConfig{Path: t.Dir, ServiceImport: t.ServiceImport, TypesRoot: t.TypesFrom}
		if t.Lang == config.LangTS {
			cfg.TsOut = append(cfg.TsOut, item)
		} else {
			cfg.JsOut = append(cfg.JsOut, item)
		}
	}
	return cfg
}

// Generate 在已规范化的配置上生成前端 API 客户端（TS/JS）与 runtime helper。
// 与 registry 段互不依赖：只认 google.api.http 注解与 targets 里声明的目录。
// Generate 在已规范化的配置上生成前端 API 客户端（TS/JS）与 runtime helper。
//
// 全程先写内存，全部成功后按目录整体替换（<dir>.tmp → <dir>）。
// 生成中途失败不会留下半个目录——旧客户端保持可用，错误信息也不会被
// 「文件已删光」的编译错误淹没。这与 registry 段写 gen/ 的策略一致。
func Generate(gen *protogen.Plugin, cfg *config.FrontendAPI) error {
	pluginCfg := toPluginConfig(cfg)

	files := make(map[string][]byte)
	tsDirsWritten := make(map[string]string)
	jsDirsWritten := make(map[string]string)

	for _, f := range gen.Files {
		if !f.Generate {
			continue
		}
		for _, service := range f.Services {
			if err := generateFrontendApi(gen, f, service, pluginCfg, files, tsDirsWritten, jsDirsWritten); err != nil {
				return err
			}
		}
	}

	// helper 与各服务文件一起提交，避免「helper 是新的、Api.ts 是旧的」。
	for dir, serviceImport := range tsDirsWritten {
		content := strings.ReplaceAll(grpcGatewayHelperTS, "BASE_SERVICE_IMPORT_PLACEHOLDER", serviceImport)
		files[filepath.Join(dir, "grpcGatewayHelper.ts")] = []byte(content)
	}
	for dir, serviceImport := range jsDirsWritten {
		content := strings.ReplaceAll(grpcGatewayHelperJS, "BASE_SERVICE_IMPORT_PLACEHOLDER", serviceImport)
		files[filepath.Join(dir, "grpcGatewayHelper.js")] = []byte(content)
	}

	dirs := make([]string, 0, len(pluginCfg.TsOut)+len(pluginCfg.JsOut))
	for _, o := range pluginCfg.TsOut {
		dirs = append(dirs, o.Path)
	}
	for _, o := range pluginCfg.JsOut {
		dirs = append(dirs, o.Path)
	}
	return commitOutput(dirs, files)
}

// commitOutput 把内存里的生成结果整体替换进各 target 目录。
// 目录必须先存在：配置了一个不存在的目录是配置错误，不静默跳过（否则你会以为生成了）。
func commitOutput(dirs []string, files map[string][]byte) error {
	for _, dir := range dirs {
		if fi, err := os.Stat(dir); err != nil || !fi.IsDir() {
			return fmt.Errorf("frontend_api.targets 里的目录不存在: %s（生成器不替你造目录）", dir)
		}
	}

	byDir := make(map[string]map[string][]byte, len(dirs))
	for _, dir := range dirs {
		byDir[dir] = map[string][]byte{}
	}
	for path, content := range files {
		root := longestPrefix(dirs, path)
		if root == "" {
			return fmt.Errorf("生成物 %s 不在任何 target 目录下（生成器只写 targets 里声明的目录）", path)
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return fmt.Errorf("计算 %s 相对 %s 的路径失败: %w", path, root, err)
		}
		byDir[root][rel] = content
	}

	for _, dir := range dirs {
		if err := replaceDir(dir, byDir[dir]); err != nil {
			return err
		}
	}
	return nil
}

// longestPrefix 返回包含 path 的最长 target 目录（targets 理论上可以嵌套）。
func longestPrefix(dirs []string, path string) string {
	best := ""
	for _, dir := range dirs {
		if strings.HasPrefix(path, dir+string(filepath.Separator)) && len(dir) > len(best) {
			best = dir
		}
	}
	return best
}

// replaceDir 用 files 的内容整体替换 dir：先写 <dir>.tmp，成功后再换名。
// 换名失败会把旧目录还原，绝不出现「旧目录已删、新目录没写成」。
func replaceDir(dir string, files map[string][]byte) error {
	tmp, prev := dir+".tmp", dir+".prev"
	if err := os.RemoveAll(tmp); err != nil {
		return fmt.Errorf("清理临时目录 %s: %w", tmp, err)
	}
	for rel, content := range files {
		dst := filepath.Join(tmp, rel)
		if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
			os.RemoveAll(tmp)
			return fmt.Errorf("创建目录 %s: %w", filepath.Dir(dst), err)
		}
		if err := os.WriteFile(dst, content, 0o644); err != nil {
			os.RemoveAll(tmp)
			return fmt.Errorf("写入 %s: %w", dst, err)
		}
	}
	// 一个服务都没有时也要留下空目录（保持「只保留本次生成物」的语义）。
	if err := os.MkdirAll(tmp, 0o755); err != nil {
		return fmt.Errorf("创建 %s: %w", tmp, err)
	}
	if err := os.RemoveAll(prev); err != nil {
		os.RemoveAll(tmp)
		return fmt.Errorf("清理 %s: %w", prev, err)
	}
	if err := os.Rename(dir, prev); err != nil {
		os.RemoveAll(tmp)
		return fmt.Errorf("备份 %s: %w", dir, err)
	}
	if err := os.Rename(tmp, dir); err != nil {
		if rerr := os.Rename(prev, dir); rerr != nil {
			return fmt.Errorf("替换 %s 失败且回滚失败（旧目录在 %s）: %v / %v", dir, prev, err, rerr)
		}
		return fmt.Errorf("替换 %s 失败（已回滚）: %w", dir, err)
	}
	return os.RemoveAll(prev)
}

// getProtoRelDir 从 proto 文件路径推导相对目录
func getProtoRelDir(protoFilePath string) string {
	p := strings.ReplaceAll(protoFilePath, "\\", "/")
	p = strings.TrimPrefix(p, "proto/")
	p = strings.TrimPrefix(p, "proto_third/")
	dir := filepath.Dir(p)
	if dir == "." || dir == "/" {
		return ""
	}
	return dir
}

// generateFrontendApi 生成前端 API 文件
func generateFrontendApi(gen *protogen.Plugin, file *protogen.File, service *protogen.Service, config *PluginConfig, files map[string][]byte, tsDirsWritten, jsDirsWritten map[string]string) error {
	// 服务名称（去掉 Service 后缀）
	serviceName := strings.TrimSuffix(string(service.Desc.Name()), "Service")

	// 生成 API 文件名（例如：GoodsService -> goodsApi）
	apiFileName := naming.LowerFirst(serviceName) + "Api"

	// 提取方法信息
	var methods []MethodInfo
	for _, method := range service.Methods {
		httpRule := httpx.Extract(method)
		isStreamingClient := method.Desc.IsStreamingClient()
		isStreamingServer := method.Desc.IsStreamingServer()

		// 只有带 HTTP 注解的方法才生成前端接口（含 SSE server-streaming；mux bidi 客户端已退役）
		if httpRule != nil {
			requestType := string(method.Input.Desc.Name())
			responseType := string(method.Output.Desc.Name())

			path := httpRule.Path
			httpMethod := strings.ToLower(httpRule.Method)

			methodInfo := MethodInfo{
				MethodName:        string(method.Desc.Name()),
				HttpPath:          path,
				HttpMethod:        httpMethod,
				RequestType:       requestType,
				ResponseType:      responseType,
				IsStreamingServer: isStreamingServer,
				IsStreamingClient: isStreamingClient,
				ReqBytesPaths:     bytesPathsToJSLiteral(collectBytesPaths(method.Input.Desc)),
				RespBytesPaths:    bytesPathsToJSLiteral(collectBytesPaths(method.Output.Desc)),
			}
			methods = append(methods, methodInfo)
		}
	}

	// 如果没有方法，跳过生成
	if len(methods) == 0 {
		return nil
	}

	// 收集所有使用的类型及其所在的 proto 文件
	// 用于生成正确的 import 语句
	typeImports := collectTypeImports(gen, service, methods)

	if len(config.TsOut) == 0 && len(config.JsOut) == 0 {
		return nil
	}

	for _, outputPathConfig := range config.TsOut {
		serviceImport := outputPathConfig.ServiceImport

		tsDirsWritten[outputPathConfig.Path] = serviceImport

		// 准备模板数据
		data := ServiceInfo{
			ServiceName:   serviceName,
			ApiFileName:   apiFileName,
			Methods:       methods,
			ServiceImport: serviceImport,
			TypesRoot:     outputPathConfig.TypesRoot,
			TypeImports:   typeImports,
			ProtoFilePath: file.Desc.Path(),
		}

		// 生成 TypeScript 代码
		code := generateTypeScriptCode(data)
		fileName := naming.LowerFirst(serviceName) + "Api.ts"

		// 从 proto 文件路径推导相对目录并拼装目标目录
		protoFilePath := file.Desc.Path()
		relDir := getProtoRelDir(protoFilePath)
		targetDir := outputPathConfig.Path
		if relDir != "" {
			targetDir = filepath.Join(outputPathConfig.Path, relDir)
		}

		// 只登记路径，落盘统一在 commitOutput（整体替换，失败不留半套）。
		files[filepath.Join(targetDir, fileName)] = code
	}

	for _, outputPathConfig := range config.JsOut {
		serviceImport := outputPathConfig.ServiceImport

		jsDirsWritten[outputPathConfig.Path] = serviceImport

		data := ServiceInfo{
			ServiceName:   serviceName,
			ApiFileName:   apiFileName,
			Methods:       methods,
			ServiceImport: serviceImport,
			ProtoFilePath: file.Desc.Path(),
		}
		// 按目标目录所属项目的 prettier 配置生成，避免生成后被编辑器/lint-staged 重新格式化
		code := generateJavaScriptCode(data, resolvePrettierConfig(outputPathConfig.Path))
		fileName := naming.LowerFirst(serviceName) + "Api.js"

		// 从 proto 文件路径推导相对目录并拼装目标目录
		protoFilePath := file.Desc.Path()
		relDir := getProtoRelDir(protoFilePath)
		targetDir := outputPathConfig.Path
		if relDir != "" {
			targetDir = filepath.Join(outputPathConfig.Path, relDir)
		}

		files[filepath.Join(targetDir, fileName)] = code
	}

	return nil
}

